// The pages in vi/, de/, ja/, zh/, zh-hant/, ru/, ko/ and es/ are generated from index.html and locales/ by
// scripts/build-pages.mjs and committed (the deploy has no build step). These tests fail when they
// are out of date, and check the SEO parts every page must carry.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANGUAGES } from '../src/ui/i18n.js';
import { renderAll, loadStrings, ORIGIN } from '../scripts/build-pages.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => readFileSync(join(root, file), 'utf8');
const urlOf = (language) => (language.path ? `${ORIGIN}/${language.path}/` : `${ORIGIN}/`);
const fileOf = (language) => (language.path ? `${language.path}/index.html` : 'index.html');

test('generated pages are up to date (run `npm run pages` if this fails)', async () => {
  const pages = await renderAll();
  assert.equal(pages.length, LANGUAGES.length - 1);
  for (const { file, text } of pages) {
    assert.ok(existsSync(join(root, file)), `${file} is missing: run \`npm run pages\``);
    assert.equal(read(file), text, `${file} is out of date: run \`npm run pages\` and commit the result`);
    assert.ok(text.startsWith('<!-- GENERATED by scripts/build-pages.mjs'), `${file} starts with the generated-file note`);
  }
});

test('every page: lang, canonical itself, og:url, JSON-LD url, and the same hreflang set', async () => {
  const expectedAlternates = [...LANGUAGES.map((l) => [l.code, urlOf(l)]), ['x-default', `${ORIGIN}/`]];
  for (const language of LANGUAGES) {
    const html = read(fileOf(language));
    const where = fileOf(language);
    assert.match(html, new RegExp(`<html lang="${language.code}">`), where);
    assert.equal(html.match(/<link rel="canonical" href="([^"]+)"/)[1], urlOf(language), `${where} canonical`);
    assert.equal(html.match(/<meta property="og:url" content="([^"]+)"/)[1], urlOf(language), `${where} og:url`);
    assert.equal(html.match(/"url": "([^"]+)"/)[1], urlOf(language), `${where} JSON-LD url`);
    const alternates = [...html.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g)].map((m) => [m[1], m[2]]);
    assert.deepEqual(alternates, expectedAlternates, `${where} hreflang`);
    const strings = await loadStrings(language.code);
    assert.equal(html.match(/<meta property="og:title" content="([^"]*)"/)[1], strings['meta.title'], `${where} og:title`);
    assert.equal(html.match(/<meta property="og:description" content="([^"]*)"/)[1], strings['meta.description'], `${where} og:description`);
    assert.equal(html.match(/<meta name="description"[^>]*content="([^"]*)"/)[1], strings['meta.description'], `${where} description`);
    assert.equal(html.match(/<title[^>]*>([^<]*)<\/title>/)[1], strings['meta.title'], `${where} title`);
  }
});

test('every page uses root-absolute asset paths and preloads its own locale', () => {
  for (const language of LANGUAGES) {
    const html = read(fileOf(language));
    const where = fileOf(language);
    for (const [, attr, path] of html.matchAll(/\s(href|src)="([^"]+)"/g)) {
      assert.ok(!/^(styles|assets|src|locales)\//.test(path), `${where}: ${attr}="${path}" must start with /`);
    }
    const locales = [...html.matchAll(/<link rel="modulepreload" href="\/locales\/([^"]+)\.js"/g)].map((m) => m[1]);
    assert.deepEqual(locales, language.code === 'en' ? ['en'] : ['en', language.code], where);
  }
});

test('only "/" carries the language redirect', () => {
  assert.match(read('index.html'), /<!-- Language redirect/);
  for (const language of LANGUAGES.filter((l) => l.path)) assert.doesNotMatch(read(fileOf(language)), /Language redirect|flux-rc:lang'\)/, fileOf(language));
});

test('a translated page really shows its language in the HTML (no JS needed)', async () => {
  const vi = read('vi/index.html');
  assert.match(vi, /<h2 id="h-about" data-i18n="about.title">Về trang này<\/h2>/);
  assert.match(read('de/index.html'), /id="btn-lang"[^>]*>DE<\/button>/);
});

test('sitemap.xml lists every page with the same alternates', () => {
  const xml = read('sitemap.xml');
  const urls = [...xml.matchAll(/<url>([\s\S]*?)<\/url>/g)].map((m) => m[1]);
  assert.deepEqual(urls.map((u) => u.match(/<loc>([^<]+)<\/loc>/)[1]), LANGUAGES.map(urlOf));
  const expectedAlternates = [...LANGUAGES.map((l) => [l.code, urlOf(l)]), ['x-default', `${ORIGIN}/`]];
  for (const u of urls) {
    const alternates = [...u.matchAll(/<xhtml:link rel="alternate" hreflang="([^"]+)" href="([^"]+)"\s*\/>/g)].map((m) => [m[1], m[2]]);
    assert.deepEqual(alternates, expectedAlternates);
  }
});
