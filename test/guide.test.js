// The PIN guide page (guide/index.html): its generated content is current, every PIN is on the page, and the SEO basics are in place.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import s from '../locales/guide/en.js';
import { PINS } from '../src/data/pins.js';
import { LANGUAGES } from '../src/ui/i18n.js';
import { renderAll, guideFile, guideUrl, loadGuideStrings } from '../scripts/build-guide.mjs';
import { ORIGIN } from '../scripts/build-pages.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'guide/index.html'), 'utf8');

const read = (file) => readFileSync(join(root, file), 'utf8');

test('every generated guide page is up to date (run `npm run guide`)', async () => {
  const pages = await renderAll();
  assert.ok(pages.some((p) => p.file === 'guide/index.html'));
  for (const { file, text } of pages) {
    assert.equal(read(file), text, `${file} is out of date: run \`npm run guide\` and commit the result`);
    if (file !== 'guide/index.html') assert.ok(text.startsWith('<!-- GENERATED by scripts/build-guide.mjs'), `${file} starts with the generated-file note`);
  }
});

test('a guide page exists for every language that has guide strings, and the English page has the language redirect', async () => {
  for (const language of LANGUAGES) {
    if (await loadGuideStrings(language.code)) assert.ok(existsSync(join(root, guideFile(language))), `${guideFile(language)} is missing: run \`npm run guide\``);
  }
  assert.match(html, /<!-- Language redirect/);
  for (const language of LANGUAGES.filter((l) => l.path)) {
    if (existsSync(join(root, guideFile(language)))) assert.doesNotMatch(read(guideFile(language)), /Language redirect|flux-rc:lang'\)/, guideFile(language));
  }
});

test('every guide page: lang, canonical itself, og:url, same hreflang set, home links and language button in its language', async () => {
  const expected = [...LANGUAGES.map((l) => [l.code, guideUrl(l)]), ['x-default', `${ORIGIN}/guide/`]];
  for (const language of LANGUAGES) {
    const file = guideFile(language);
    if (!existsSync(join(root, file))) continue;
    const page = read(file);
    assert.match(page, new RegExp(`<html lang="${language.code}">`), file);
    assert.equal(page.match(/<link rel="canonical" href="([^"]+)"/)[1], guideUrl(language), `${file} canonical`);
    assert.equal(page.match(/<meta property="og:url" content="([^"]+)"/)[1], guideUrl(language), `${file} og:url`);
    assert.deepEqual([...page.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g)].map((m) => [m[1], m[2]]), expected, `${file} hreflang`);
    const home = language.path ? `/${language.path}/` : '/';
    assert.match(page, new RegExp(`<a class="wordmark" href="${home}">`), `${file} wordmark`);
    assert.match(page, new RegExp(`<a class="g-back" href="${home}">`), `${file} programmer link`);
    assert.match(page, new RegExp(`id="btn-lang"[^>]*>${language.short}</button>`), `${file} language button`);
    assert.equal((page.match(/<h1[ >]/g) || []).length, 1, `${file} h1`);
    const ld = JSON.parse(page.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
    assert.deepEqual(ld['@graph'].map((n) => n['@type']), ['HowTo', 'FAQPage'], file);
    const strings = await loadGuideStrings(language.code);
    assert.equal(ld['@graph'][0].name, strings.howtoName, `${file} JSON-LD in its language`);
  }
});

test('every PIN has a card with its click pattern, and a FAQ entry', () => {
  for (const pin of PINS) {
    assert.match(html, new RegExp(`id="${pin.id}" data-boards="${pin.boards.join(' ')}"`), pin.id);
    assert.ok(html.includes(s.faqQuestion.replace('{pin}', pin.digits.join('')).replace('{board}', pin.boards.length === 2 ? s.faqBoth : s.faqV2)), `FAQ for ${pin.id}`);
  }
  assert.equal((html.match(/class="g-pattern"/g) || []).length, PINS.length);
});

test('SEO basics: one h1, canonical, indexable, title and description sized, JSON-LD parses', () => {
  assert.equal((html.match(/<h1[ >]/g) || []).length, 1);
  assert.match(html, /<link rel="canonical" href="https:\/\/flux-rc\.stevensdesk\.com\/guide\/">/);
  assert.ok(!/noindex/.test(html));
  const title = html.match(/<title>([^<]+)<\/title>/)[1];
  const description = html.match(/<meta name="description" content="([^"]+)"/)[1];
  assert.ok(title.length <= 70 && /371/.test(title), title);
  assert.ok(description.length >= 100 && description.length <= 170, `${description.length}`);
  const ld = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
  assert.deepEqual(ld['@graph'].map((n) => n['@type']), ['HowTo', 'FAQPage']);
});

test('the name 371D appears only in the v1 description, the title, the meta tags and the header tagline', () => {
  // The header tagline is the programmer's own (same wrapping, so the header does not move between the pages) and names the light engines.
  const allowed = /<title>|og:title|name="description"|also sold as the 371D|<p class="tagline">/;
  const lines = html.split('\n').filter((line) => line.includes('371D'));
  assert.ok(lines.length >= 3);
  for (const line of lines) assert.match(line, allowed, line.trim().slice(0, 80));
  assert.ok(html.includes('371 v1'));
});

test('every visible FAQ question is on the page as card text', () => {
  const ld = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
  const body = html.split('<main')[1];
  for (const q of ld['@graph'][1].mainEntity) assert.ok(body.includes(`>${q.name}<`), q.name);
});
