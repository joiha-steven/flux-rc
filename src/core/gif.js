// Frames -> 1x1 animated GIF89a, byte for byte as the original. See docs/protocol.md section 3.

const ascii = (s) => [...s].map((c) => c.charCodeAt(0));

/**
 * @param {{ color: 'lead'|'white'|'black', cs: number }[]} frames
 * @returns {Uint8Array}
 */
export function framesToGif(frames) {
  const out = [
    ...ascii('GIF89a'),
    0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00, // 1x1, global colour table of 2 entries
    0x00, 0x00, 0x00, 0xff, 0xff, 0xff, // black, white
    0x21, 0xff, 0x0b, ...ascii('NETSCAPE2.0'), 0x03, 0x01, 0x00, 0x00, 0x00, // loop forever
  ];
  for (const { color, cs } of frames) {
    const lead = color === 'lead';
    out.push(0x21, 0xf9, 0x04, 0x04, cs & 0xff, (cs >> 8) & 0xff, 0x00, 0x00);
    out.push(0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, lead ? 0x80 : 0x00);
    if (lead) out.push(0x32, 0x96, 0x00, 0x00, 0x00, 0x00);
    out.push(0x02, 0x02, color === 'white' ? 0x4c : 0x44, 0x01, 0x00);
  }
  out.push(0x3b);
  return Uint8Array.from(out);
}
