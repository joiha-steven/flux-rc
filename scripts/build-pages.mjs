// Generates one page per non-English language (<path>/index.html for every entry in LANGUAGES in src/ui/i18n.js)
// from index.html plus locales/<code>.js. Run `npm run pages` after editing index.html or any
// locale file, and commit the result: the deploy has no build step. test/pages.test.js fails
// when a generated page is out of date.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import en from '../locales/en.js';
import { LANGUAGES } from '../src/ui/i18n.js';

export const ORIGIN = 'https://flux-rc.stevensdesk.com';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The language pages to generate: every language except English (index.html is hand-written). */
export const PAGE_LANGUAGES = LANGUAGES.filter((l) => l.path);

const escapeText = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escapeAttr = (s) => escapeText(s).replace(/"/g, '&quot;');

/** Locale strings with English filling any key the locale lacks, as t() does in the browser. */
export async function loadStrings(code) {
  if (code === 'en') return en;
  const locale = (await import(pathToFileURL(join(root, 'locales', `${code}.js`)).href)).default;
  return { ...en, ...locale };
}

/** Fills data-i18n text and data-i18n-attr attributes. Parsing mirrors test/i18n.test.js. */
function translate(html, strings) {
  const get = (key) => {
    if (typeof strings[key] !== 'string') throw new Error(`build-pages: no text for "${key}"`);
    return strings[key];
  };
  const withAttrs = html.replace(/<\w+[^>]*\sdata-i18n-attr="[^"]+"[^>]*>/g, (tag) => {
    let out = tag;
    for (const pair of tag.match(/data-i18n-attr="([^"]+)"/)[1].split(';')) {
      const [attr, key] = pair.split(':');
      out = out.replace(new RegExp(`(\\s${attr}=")[^"]*(")`), (_, open, close) => open + escapeAttr(get(key)) + close);
    }
    return out;
  });
  return withAttrs.replace(/<(\w+)([^>]*\sdata-i18n="([^"]+)"[^>]*)>([\s\S]*?)<\/\1>/g, (_, tag, attrs, key, inner) => {
    const slots = new Map([...inner.matchAll(/<a\b([^>]*data-i18n-slot="(\w+)"[^>]*)>[\s\S]*?<\/a>/g)]
      .map((m) => [m[2], `<a${m[1]}>${escapeText(get(m[1].match(/data-i18n="([^"]+)"/)[1]))}</a>`]));
    const body = slots.size
      ? get(key).split(/\{(\w+)\}/).map((piece, i) => (i % 2 === 0 ? escapeText(piece) : slots.get(piece) ?? `{${piece}}`)).join('')
      : escapeText(get(key));
    return `<${tag}${attrs}>${body}</${tag}>`;
  });
}

/** The generated page for one language: `html` is the text of index.html, `strings` from loadStrings(). */
export function renderPage(html, language, strings) {
  const url = `${ORIGIN}/${language.path}/`;
  const swap = (source, pattern, replacement) => {
    if (!pattern.test(source)) throw new Error(`build-pages: index.html no longer matches ${pattern}`);
    return source.replace(pattern, replacement);
  };
  let page = html;
  page = swap(page, /^[ \t]*<!-- Language redirect[\s\S]*?<\/script>\n/m, '');
  page = swap(page, /<html lang="en">/, `<html lang="${language.code}">`);
  page = swap(page, /(<link rel="canonical" href=")[^"]*"/, `$1${url}"`);
  page = swap(page, /(<meta property="og:url" content=")[^"]*"/, `$1${url}"`);
  page = swap(page, /("url": ")[^"]*"/, `$1${url}"`);
  page = swap(page, /(<meta property="og:title" content=")[^"]*"/, () => `<meta property="og:title" content="${escapeAttr(strings['meta.title'])}"`);
  page = swap(page, /(<meta property="og:description" content=")[^"]*"/, () => `<meta property="og:description" content="${escapeAttr(strings['meta.description'])}"`);
  page = swap(page, /(<link rel="modulepreload" href="\/locales\/en\.js">\n)/, `$1  <link rel="modulepreload" href="/locales/${language.code}.js">\n`);
  page = swap(page, /(id="btn-lang"[^>]*>)[^<]*(<\/button>)/, (_, open, close) => open + escapeText(language.short) + close);
  page = translate(page, strings);
  const note = `<!-- GENERATED by scripts/build-pages.mjs from index.html and locales/${language.code}.js. Do not edit by hand: change those files and run \`npm run pages\`. -->\n`;
  return note + page;
}

/** Every generated page as { file, text }, file relative to the repo root. */
export async function renderAll() {
  const html = readFileSync(join(root, 'index.html'), 'utf8');
  return Promise.all(PAGE_LANGUAGES.map(async (language) => ({
    file: `${language.path}/index.html`,
    text: renderPage(html, language, await loadStrings(language.code)),
  })));
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const { file, text } of await renderAll()) {
    mkdirSync(join(root, dirname(file)), { recursive: true });
    writeFileSync(join(root, file), text);
    console.log(`wrote ${file}`);
  }
}
